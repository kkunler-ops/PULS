export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "de";
  const raw = (navigator.languages?.[0] || navigator.language || "de").toLowerCase();
  const short = raw.slice(0, 2);
  if (short === "no" || short === "nn") return "nb";
  if (isLocale(short)) return short;
  return "de";
}

export function t(locale: Locale, key: keyof Messages, vars?: Record<string, string>): string {
  let value = messages[locale][key];
  if (!vars) return value;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, replacement);
  }
  return value;
}

export function buildAlarmEmail(locale: Locale, name: string) {
  const safeName = name.trim() || "PULS";
  const vars = { name: safeName };
  return {
    subject: t(locale, "emailSubject", vars),
    text: [
      t(locale, "emailGreeting"),
      "",
      t(locale, "emailBody", vars),
      "",
      t(locale, "emailClose"),
    ].join("\n"),
  };
}
